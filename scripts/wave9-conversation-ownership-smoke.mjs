import assert from "node:assert/strict";
import { createRequire } from "node:module";
process.env.SUPABASE_URL ||= "https://example.supabase.co";
process.env.SUPABASE_SERVICE_ROLE_KEY ||= "test-service-role-key";
const require = createRequire(import.meta.url);
const { publicConversationActor, threadScopeMatches, authorizeConversationThread } = require("../dist/oyi-core/context/conversationOwnership.js");
const { supabaseAdmin } = require("../dist/supabase/supabaseClient.js");
const a = publicConversationActor("random-session-a"), b = publicConversationActor("random-session-b");
assert.notEqual(a.id, b.id);
assert.equal(a.id, publicConversationActor("random-session-a").id);
assert.match(a.id, /^[a-f0-9-]{36}$/);
assert.equal(a.role, "guest");
assert.deepEqual(a.permissions, []);
const threadId = "11111111-1111-4111-a111-111111111111";
const context = { actor: a, oisContext: null, input: { surface: "public_corporate", thread_id: threadId } };
const row = { id: threadId, user_id: a.id, surface: "public_corporate", estate_id: null, home_id: null };
assert.equal(threadScopeMatches(row, context), true);
assert.equal(threadScopeMatches(row, { ...context, actor: b }), false);
assert.equal(threadScopeMatches({ ...row, surface: "office_internal" }, context), false);
assert.equal(threadScopeMatches({ ...row, home_id: "private-home" }, context), false);
let response = { data: row, error: null }, queries = 0;
supabaseAdmin.from = table => {
  assert.equal(table, "oyi_conversation_threads"); queries++;
  const query = { select: () => query, eq: (column, id) => { assert.equal(column, "id"); assert.equal(id, threadId); return query; }, maybeSingle: async () => response };
  return query;
};
assert.equal(await authorizeConversationThread(context), context);
await assert.rejects(authorizeConversationThread({ ...context, actor: b }), error => error.status === 403);
response = { data: null, error: { message: "db unavailable" } };
await assert.rejects(authorizeConversationThread(context), error => error.status === 503);
response = { data: null, error: null };
assert.equal((await authorizeConversationThread(context)).input.thread_id, null);
assert.equal((await authorizeConversationThread({ ...context, input: { ...context.input, thread_id: "client-temporary" } })).input.thread_id, null);
assert.equal(queries, 4);
console.log("PASS session separation, actor/surface/home boundary, DB error fail-closed, unowned IDs discarded");
