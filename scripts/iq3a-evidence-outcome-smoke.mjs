for(const [scopeStatus,status]of [['unsupported','scope_unsupported'],['insufficient','scope_insufficient']]) {
 const r=check({scope:scopeStatus,source_total:19},status);assert.equal(r.records.length,0);assert.equal(r.source_total,null);assert.equal(r.effective_scope,null);
}
const denied=check({authority:'denied',source_total:19},'authority_denied');assert.equal(denied.record_count,0);assert.equal(denied.source_total,null);
check({effective_scope:null},'scope_insufficient');
check({requested_scope:{...scope,building_id:'building-b'}},'scope_unsupported');
check({effective_scope:{...scope,home_id:'home-b'}},'scope_unsupported');
const crossHome=check({records:[{...record,authorised_scope:{...scope,home_id:'home-b'}}],source_total:1},'authority_denied');assert.equal(crossHome.source_total,null);assert.equal(crossHome.record_count,0);
check({requested_scope:{...scope,room_id:'room-a'}},'scope_unsupported');
check({freshness:'stale'},'stale');
check({freshness:'unknown',records:[]},'available_partial');
check({freshness:'historical',records:[]},'available_partial');
const historical=check({freshness:'historical',lifecycle:[{evidence_id:record.evidence_id,relevance:'historical'}]},'available_complete');assert.equal(historical.lifecycle[0].relevance,'historical');
const truncated=check({source_total:39,records:Array.from({length:20},(_,i)=>({...record,evidence_id:String(i)}))},'available_partial');assert.equal(truncated.complete,false);assert.equal(truncated.truncated,true);
check({truncated:true,records:[]},'available_partial');
