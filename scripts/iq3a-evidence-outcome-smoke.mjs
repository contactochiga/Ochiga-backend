const check=(input,status,zero=false)=>{const r=evidenceReadOutcome({...proof,...input});assert.equal(r.status,status);assert.equal(r.zero_proven,zero);assertions++;return r;};
check({},'available_complete');
check({records:[]},'available_zero',true);
check({complete:false},'available_partial');
