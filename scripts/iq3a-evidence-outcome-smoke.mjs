import assert from 'node:assert/strict';
import { evidenceReadOutcome, withinEvidenceDeadline } from '../dist/oyi-core/evidence/EvidenceReadOutcome.js';
const scope={estate_id:'synthetic-estate',home_id:'synthetic-home-a',room_id:null};
